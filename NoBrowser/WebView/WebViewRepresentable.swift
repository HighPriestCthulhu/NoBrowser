import SwiftUI
import WebKit
import os

struct WebViewRepresentable: UIViewRepresentable {
    let url: URL
    let model: WebViewModel

    /// The script and its message handler live in WebKit's `.defaultClient`
    /// content world, not the page's. The DOM is shared between worlds, but
    /// JavaScript globals are not, so the page can't call `__nbReveal`, post
    /// fake `nbImageTap` messages, or see `window.__nbInit`.
    static let contentWorld = WKContentWorld.defaultClient
    static let messageHandlerName = "nbImageTap"

    // Grayscale strategy: a fixed, pointer-events-none overlay div with
    // backdrop-filter: grayscale(100%) desaturates everything painted
    // beneath it. Revealing an image = cloning it ABOVE the overlay
    // (later sibling, higher z-index), which reuses the page's own
    // already-decoded bytes — correct cookies/Referer, works for blob:
    // and srcset, and scrolls/zooms with the page for free.
    //
    // The overlay is a nudge, not a security boundary. A MutationObserver
    // re-adds it if removed and resets its attributes if a page restyles
    // it, but a determined page can still defeat a cosmetic overlay (for
    // example by stacking its own content at the maximum z-index or using
    // CSS filters on <html>). That's accepted.
    //
    // Known limitation: images inside iframes render grayscale but taps
    // in subframes can't be intercepted, so they can't be unlocked.
    private static let grayscaleScript = """
    (function() {
        if (window.__nbInit) { return; }
        window.__nbInit = true;

        var Z = 2147483646;
        var OVERLAY_CSS = 'position:fixed !important;top:0 !important;left:0 !important;' +
            'right:0 !important;bottom:0 !important;width:auto !important;height:auto !important;' +
            'display:block !important;visibility:visible !important;opacity:1 !important;' +
            'z-index:' + Z + ' !important;pointer-events:none !important;' +
            '-webkit-backdrop-filter:grayscale(100%) !important;backdrop-filter:grayscale(100%) !important;';

        function resetOverlay(ov) {
            var names = [];
            for (var i = 0; i < ov.attributes.length; i++) { names.push(ov.attributes[i].name); }
            names.forEach(function(n) { ov.removeAttribute(n); });
            ov.style.cssText = OVERLAY_CSS;
        }

        function makeOverlay() {
            var ov = document.createElement('div');
            resetOverlay(ov);
            document.documentElement.appendChild(ov);
            return ov;
        }
        var overlay = makeOverlay();

        var observer = new MutationObserver(function(records) {
            var restyled = records.some(function(r) {
                return r.type === 'attributes' && r.target === overlay;
            });
            if (!document.documentElement.contains(overlay)) {
                overlay = makeOverlay();
                observer.observe(overlay, { attributes: true });
            } else if (restyled) {
                resetOverlay(overlay);
            }
            // Drop the records generated by our own fixes above.
            observer.takeRecords();
        });
        observer.observe(document.documentElement, { childList: true });
        observer.observe(overlay, { attributes: true });

        var pending = null;

        window.__nbReveal = function() {
            var img = pending;
            if (!img || !document.contains(img)) { return; }
            var r = img.getBoundingClientRect();
            var cs = getComputedStyle(img);
            var clone = document.createElement('img');
            clone.src = img.currentSrc || img.src;
            clone.setAttribute('data-nb-clone', '1');
            clone.style.cssText = 'position:absolute;margin:0;padding:0;border:0;' +
                'z-index:' + (Z + 1) + ';' +
                'left:' + (r.left + window.pageXOffset) + 'px;' +
                'top:' + (r.top + window.pageYOffset) + 'px;' +
                'width:' + r.width + 'px;height:' + r.height + 'px;' +
                'object-fit:' + (cs.objectFit || 'fill') + ';' +
                'border-radius:' + cs.borderRadius + ';';
            document.documentElement.appendChild(clone);
        };

        var MIN_SIZE = 32;
        document.addEventListener('click', function(e) {
            var t = e.target;
            if (t && t.getAttribute && t.getAttribute('data-nb-clone')) {
                e.preventDefault();
                e.stopPropagation();
                t.remove();
                return;
            }
            var img = t && t.closest ? t.closest('img') : null;
            if (!img) { return; }
            var src = img.currentSrc || img.src;
            if (!src) { return; }
            var r = img.getBoundingClientRect();
            if (r.width < MIN_SIZE || r.height < MIN_SIZE) { return; }
            e.preventDefault();
            e.stopPropagation();
            pending = img;
            window.webkit.messageHandlers.\(messageHandlerName).postMessage({ src: src });
        }, true);
    })();
    """

    func makeUIView(context: Context) -> WKWebView {
        let config = WKWebViewConfiguration()
        let contentController = WKUserContentController()
        contentController.addUserScript(WKUserScript(
            source: Self.grayscaleScript,
            injectionTime: .atDocumentStart,
            forMainFrameOnly: true,
            in: Self.contentWorld
        ))
        contentController.add(context.coordinator, contentWorld: Self.contentWorld, name: Self.messageHandlerName)
        config.userContentController = contentController

        let webView = WKWebView(frame: .zero, configuration: config)
        webView.navigationDelegate = context.coordinator
        webView.uiDelegate = context.coordinator
        webView.allowsBackForwardNavigationGestures = true
        model.webView = webView
        webView.load(URLRequest(url: url))
        return webView
    }

    func updateUIView(_ webView: WKWebView, context: Context) {}

    static func dismantleUIView(_ webView: WKWebView, coordinator: Coordinator) {
        webView.configuration.userContentController.removeScriptMessageHandler(
            forName: messageHandlerName,
            contentWorld: contentWorld
        )
    }

    func makeCoordinator() -> Coordinator {
        Coordinator(model: model)
    }

    // MARK: - Navigation policy

    /// Which URLs the web view may navigate to. Everything else (tel:, sms:,
    /// mailto:, itms-apps:, custom app schemes, file:, top-level data:) is
    /// cancelled: NoBrowser never hands a page's link off to another app.
    ///
    /// - http, https: ordinary pages.
    /// - blob: object URLs that some pages navigate to or load in frames.
    /// - about:blank, about:srcdoc: empty and inline-HTML frames.
    /// - data: allowed in subframes only, never as a top-level page.
    static func isAllowed(_ url: URL?, isMainFrame: Bool) -> Bool {
        guard let url, let scheme = url.scheme?.lowercased() else { return false }
        switch scheme {
        case "http", "https", "blob":
            return true
        case "about":
            return url.absoluteString == "about:blank" || url.absoluteString == "about:srcdoc"
        case "data":
            return !isMainFrame
        default:
            return false
        }
    }

    final class Coordinator: NSObject, WKNavigationDelegate, WKUIDelegate, WKScriptMessageHandler {
        private let model: WebViewModel
        private let log = Logger(subsystem: Bundle.main.bundleIdentifier ?? "NoBrowser", category: "navigation")

        init(model: WebViewModel) {
            self.model = model
        }

        // MARK: WKScriptMessageHandler

        func userContentController(_ userContentController: WKUserContentController, didReceive message: WKScriptMessage) {
            guard message.name == WebViewRepresentable.messageHandlerName,
                  message.frameInfo.isMainFrame,
                  let body = message.body as? [String: Any],
                  let src = body["src"] as? String else { return }

            if model.solvedSources.contains(src) {
                // Already solved on this page — reveal without a puzzle.
                (message.webView ?? model.webView)?.revealPendingImage()
            } else {
                model.pendingImage = TappedImage(src: src)
            }
        }

        // MARK: WKNavigationDelegate

        func webView(
            _ webView: WKWebView,
            decidePolicyFor navigationAction: WKNavigationAction,
            decisionHandler: @escaping @MainActor (WKNavigationActionPolicy) -> Void
        ) {
            let isMainFrame = navigationAction.targetFrame?.isMainFrame ?? true
            if WebViewRepresentable.isAllowed(navigationAction.request.url, isMainFrame: isMainFrame) {
                decisionHandler(.allow)
            } else {
                let scheme = navigationAction.request.url?.scheme ?? "nil"
                log.notice("Blocked navigation to scheme \(scheme, privacy: .public)")
                decisionHandler(.cancel)
            }
        }

        func webView(_ webView: WKWebView, didStartProvisionalNavigation navigation: WKNavigation!) {
            DispatchQueue.main.async {
                self.model.isLoading = true
                self.model.estimatedProgress = 0.1
                self.model.pendingImage = nil
                self.model.solvedSources.removeAll()
            }
        }

        func webView(_ webView: WKWebView, didCommit navigation: WKNavigation!) {
            syncModel(from: webView)
        }

        func webView(_ webView: WKWebView, didFinish navigation: WKNavigation!) {
            syncModel(from: webView)
            #if DEBUG
            DispatchQueue.main.async {
                self.model.debugPageDidFinish()
            }
            #endif
        }

        func webView(_ webView: WKWebView, didFail navigation: WKNavigation!, withError error: Error) {
            syncModel(from: webView)
        }

        func webView(_ webView: WKWebView, didFailProvisionalNavigation navigation: WKNavigation!, withError error: Error) {
            syncModel(from: webView)
        }

        private func syncModel(from webView: WKWebView) {
            DispatchQueue.main.async {
                self.model.sync(from: webView)
            }
        }

        // MARK: WKUIDelegate

        /// target="_blank" links and window.open(): there are no tabs, so load
        /// the request in this same web view (if its URL is allowed) and never
        /// create a second one.
        func webView(
            _ webView: WKWebView,
            createWebViewWith configuration: WKWebViewConfiguration,
            for navigationAction: WKNavigationAction,
            windowFeatures: WKWindowFeatures
        ) -> WKWebView? {
            if WebViewRepresentable.isAllowed(navigationAction.request.url, isMainFrame: true) {
                webView.load(navigationAction.request)
            } else {
                let scheme = navigationAction.request.url?.scheme ?? "nil"
                log.notice("Blocked new-window navigation to scheme \(scheme, privacy: .public)")
            }
            return nil
        }
    }
}

extension WKWebView {
    /// Clones the most recently tapped image above the greyscale overlay.
    /// Runs in the isolated content world where the injected script lives.
    func revealPendingImage() {
        evaluateJavaScript("window.__nbReveal()", in: nil, in: WebViewRepresentable.contentWorld)
    }
}
